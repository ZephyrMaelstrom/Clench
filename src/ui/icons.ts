const PALETTE: Record<string, string> = { '#': '#1b1410', '+': '#f6eedb', '*': '#e8642c' };
const ACCENTS: Record<string, string> = {
  flame: '#ffcf4a', siphon: '#d9314a', wild: '#c78bff', prism: '#7fd8ff', rot: '#9cbf3a',
  burn: '#ff7a2a', ink: '#4b4f9c', fuse: '#ffcf4a',
};

export function makeIconTextures(scene: Phaser.Scene) {
  for (const [key, rows] of Object.entries(ICONS)) {
    const h = rows.length, w = rows[0].length;
    const tex = scene.textures.createCanvas(`icon-${key}`, w, h);
    if (!tex) continue;
    const ctx = tex.getContext();
    for (let y = 0; y < h; y++) {
      for (let x = 0; x < w; x++) {
        const ch = rows[y][x];
        if (ch === '.') continue;
        ctx.fillStyle = ch === '*' ? ACCENTS[key] ?? PALETTE['*'] : PALETTE[ch];
        ctx.fillRect(x, y, 1, 1);
      }
    }
    tex.refresh();
  }
  // 1px white texture for particles.
  const px = scene.textures.createCanvas('px', 2, 2);
  if (px) { const c = px.getContext(); c.fillStyle = '#fff'; c.fillRect(0, 0, 2, 2); px.refresh(); }
}
